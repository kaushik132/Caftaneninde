<script>
    // ── Fixed Exchange Rates (USD base) ──────────────────────────────────────────
    const RATES = {
        USD: 1,
        PKR: 278.50,
        EUR: 0.92,
        GBP: 0.79,
        AED: 3.67,
        SAR: 3.75,
        INR: 92.89,
        CAD: 1.36,
        AUD: 1.53,
        TRY: 32.10,
    };
    const SYMBOLS = {
        USD: '$',
        PKR: '₨',
        EUR: '€',
        GBP: '£',
        AED: 'د.إ',
        SAR: '﷼',
        INR: '₹',
        CAD: 'C$',
        AUD: 'A$',
        TRY: '₺',
    };
    // No-decimal currencies
    const NO_DEC = ['PKR', 'INR', 'TRY', 'SAR'];

    let currentCurrency = localStorage.getItem('currency') || 'USD';
    let currentSymbol = SYMBOLS[currentCurrency] || '$';

    // ── Format a USD value into current currency ──────────────────────────────────
    function fmtPrice(usd) {
        const val = usd * (RATES[currentCurrency] || 1);
        return currentSymbol + (NO_DEC.includes(currentCurrency) ?
            Math.round(val).toLocaleString() :
            val.toFixed(2));
    }

    // ── Convert all [data-usd] elements ──────────────────────────────────────────
    function convertAllPrices() {
        document.querySelectorAll('[data-usd]').forEach(el => {
            const usd = parseFloat(el.dataset.usd);
            if (!isNaN(usd)) el.textContent = fmtPrice(usd);
        });
    }

    // ── Set Currency & Save ───────────────────────────────────────────────────────
    function setCurrency(code, symbol) {
        currentCurrency = code;
        currentSymbol = symbol || SYMBOLS[code] || '$';
        localStorage.setItem('currency', code);

        // Header badges update
        const codeEl = document.getElementById('currencyCodeDisplay');
        const symbolEl = document.getElementById('currencySymbolDisplay');
        if (codeEl) codeEl.textContent = code;
        if (symbolEl) symbolEl.textContent = symbol;

        // Desktop dropdown active state
        document.querySelectorAll('.currency-option').forEach(el => {
            const isActive = el.getAttribute('onclick')?.includes(`'${code}'`);
            el.classList.toggle('bg-[#FFF0F6]', isActive);
            el.classList.toggle('text-[#FF71A8]', isActive);
            el.classList.toggle('font-semibold', isActive);
        });

        // Mobile button active state
        document.querySelectorAll('.mobile-currency-btn').forEach(btn => {
            const isActive = btn.dataset.code === code;
            btn.classList.toggle('bg-[#FF71A8]', isActive);
            btn.classList.toggle('text-white', isActive);
            btn.classList.toggle('border-[#FF71A8]', isActive);
        });

        convertAllPrices();
    }

    // ── Init on DOM ready ─────────────────────────────────────────────────────────
    document.addEventListener('DOMContentLoaded', () => {
        setCurrency(currentCurrency, currentSymbol);
    });
</script>


